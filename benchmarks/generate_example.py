"""Generate a real AcademicForge research-plan example from the live pipeline.

The resulting Markdown is intentionally generated, not hand-written. It uses
the same retrieval, summary, and research-plan functions served by FastAPI.

    python -m benchmarks.generate_example --device mps
"""

import argparse
from datetime import datetime, timezone
import os
from pathlib import Path

from backend.config import get_config
from backend.data_pipeline import retrieve_and_rank_papers
from backend.research_plan_generator import generate_research_plan
from backend.retrieval.device import select_retrieval_device
from backend.summarizer import summarize_paper


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_QUERY = "how can retrieval augmented generation systems reduce hallucinations"
DEFAULT_OUTPUT = ROOT / "docs" / "examples" / "rag-hallucination-research-plan.md"


def markdown_link(title: str, url: str) -> str:
    return f"[{title}]({url})" if url else title


def render_example(query: str, papers: list[dict], summaries: list[str], research_plan: str, model: str) -> str:
    lines = [
        "# Reducing hallucinations in retrieval-augmented generation",
        "",
        "> Generated by `python -m benchmarks.generate_example` from live paper retrieval and the configured local model. Do not edit this file manually; rerun the command to refresh it.",
        "",
        "## Query",
        "",
        query,
        "",
        "## Retrieved papers",
        "",
    ]
    for index, paper in enumerate(papers, start=1):
        authors = ", ".join(paper.get("authors", [])[:4]) or "Authors unavailable"
        lines.extend(
            [
                f"{index}. {markdown_link(paper.get('title', 'Untitled paper'), paper.get('url') or paper.get('link') or '')}",
                f"   {authors}. Source: {paper.get('source', 'unknown')}.",
            ]
        )

    lines.extend(["", "## Paper summaries", ""])
    for index, (paper, summary) in enumerate(zip(papers, summaries), start=1):
        lines.extend([f"### {index}. {paper.get('title', 'Untitled paper')}", "", summary.strip(), ""])

    lines.extend(
        [
            "## Research Plan",
            "",
            research_plan.strip(),
            "",
            "## Generation record",
            "",
            f"- Generated at: {datetime.now(timezone.utc).isoformat()}",
            f"- Model: `{model}`",
            f"- Retrieval device: `{select_retrieval_device()}`",
        ]
    )
    return "\n".join(lines) + "\n"


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--query", default=DEFAULT_QUERY)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--papers", type=int, default=3)
    parser.add_argument("--device", choices=("auto", "cpu", "cuda", "mps"), default="auto")
    return parser.parse_args()


def main():
    args = parse_args()
    if args.papers < 2:
        raise ValueError("--papers must be at least 2 so the example is a synthesis")
    os.environ["ACADEMICFORGE_RETRIEVAL_DEVICE"] = args.device

    papers = retrieve_and_rank_papers(args.query)[:args.papers]
    if len(papers) < 2:
        raise RuntimeError("Live retrieval returned fewer than two papers; no example was written")

    config = get_config()
    summary_model = config.model_for_task_and_mode("summary", "fast")
    plan_model = config.model_for_task_and_mode("research_plan", "fast")
    summaries = [summarize_paper(paper, model=summary_model, mode="fast") for paper in papers]
    research_plan = generate_research_plan(
        papers,
        summaries=summaries,
        query=args.query,
        model=plan_model,
        mode="fast",
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_example(args.query, papers, summaries, research_plan, plan_model), encoding="utf-8")
    print(f"Wrote generated example: {args.output}")


if __name__ == "__main__":
    main()
